        public async Task<PatientDetailsForReferralSlipByVisitIdDTO> GetPatientDetailsForReferralSlipByVisitId(Guid VisitId)
        {
            using (var db = new HmisAuthContext())
            {
                var conn = _uowPatientOpenVisit.GetDbContext().Database.GetDbConnection();
                try
                {
                    DataSet ds = new DataSet();
                    SqlCommand sqlComm = new SqlCommand("[dbo].[SPGetPatientDetailsForReferralSlipByVisitId]", (SqlConnection)conn);
                    sqlComm.CommandType = CommandType.StoredProcedure;

                    if (!AppCommonMethod.IsNullOrEmptyGuid(VisitId))
                        sqlComm.Parameters.AddWithValue("@PatientOpenVisitId", VisitId);

                    SqlDataAdapter da = new SqlDataAdapter();
                    da.SelectCommand = sqlComm;
                    await Task.Run(() => da.Fill(ds));
                    List<PatientDetailsForReferralSlipByVisitIdDTO> lst = ds.Tables[0].ToList<PatientDetailsForReferralSlipByVisitIdDTO>();
                    List<PatientVitalsDetailsForReferralSlipByVisitIdDTO> vitalLst = ds.Tables[1].ToList<PatientVitalsDetailsForReferralSlipByVisitIdDTO>();
                    var patientDetails = lst.FirstOrDefault();
                    if (patientDetails != null)
                    {
                        patientDetails.Vitals = vitalLst;
                    }

                    return patientDetails;
                }
                catch (Exception)
                {
                    throw;
                }
                finally
                {
                    conn.Close();
                }
            }
        }


