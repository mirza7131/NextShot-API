        public async Task<UpdateSscStatusAndDocumentDto> UpdateSscStatusAndDocumentDto(UpdateSscStatusAndDocumentDto input)
        {
            var dbObj = await _uowPatientOpenVisit.Repository.GetById(input.PatientVisitId);

            if (AppCommonMethod.IsNullObject(dbObj))
                throw new UserFriendlyException(CommonMessageConstant.RecordNotFound);

            if (!AppCommonMethod.IsNullorZeroInt(input.SscStatus) && dbObj.SscStatus != input.SscStatus)
            {
                dbObj.SscStatus = input.SscStatus;
                if (input.SscStatus == (int)SSCStatus.Claim_Rejected)
                    dbObj.SscStatusReason = input.SscStatusReason;
                else
                    dbObj.SscStatusReason = null;
                dbObj.SscStatusUpdatedOn = DateTime.Now;
                dbObj.SscStatusUpdatedBy = _tokenService.GetUserId();
            }

            //foreach (var document in input.PatientDocuments)
                await _patientDocumentService.UpdateAndInsert(input.PatientDocuments.ToList());

            _uowPatientOpenVisit.Repository.Update(dbObj!);
            await _uowPatientOpenVisit.CommitAsync();

            return input;
        }

        public async Task<CreateOrEditOpenVisitDto> UpdatePatientVisitForSscClaimed(PatientVisitSscClaimedDto input)
        {
            var dbObj = await _uowPatientOpenVisit.Repository.GetById(input.PatientOpenVisitId!);
            //var obj = _mapper.Map(input, dbObj);
            if (input.IsSscClaimed == true)
            {
                dbObj.IsSscClaimed = input.IsSscClaimed;
                dbObj.SscClaimedDate = DateTime.Now;

            }
            else
            {
                dbObj.ReasonIfSscNotClaimed = input.ReasonIfSscNotClaimed;
                dbObj.IsSscClaimed = input.IsSscClaimed ?? false;
            }

            FillEntity(dbObj);

            _uowPatientOpenVisit.Repository.Update(dbObj!);
            await _uowPatientOpenVisit.CommitAsync();

            return _mapper.Map<CreateOrEditOpenVisitDto>(dbObj);

        }

        public async Task<CreateorEditPatientEligibleForSSCDto> UpdatePatientEligibleForSSC(CreateorEditPatientEligibleForSSCDto input)
        {

            var dbObj = await _uowPatientOpenVisit.Repository.GetById(input.PatientOpenVisitId!);

            if (AppCommonMethod.IsNullObject(dbObj))
                throw new UserFriendlyException(CommonMessageConstant.RecordNotFound);

            var obj = _mapper.Map(input, dbObj);

            obj.SscNumber = input.SscNumber;
            obj.IsEligibleForSsc = input.IsEligibleForSsc;
            if(input.IsEligibleForSsc == true)
            {
                obj.SscStatus = (int)SSCStatus.Eligible;
                obj.SscStatusReason = null;
            }
            else
            {
                obj.SscStatus = (int)SSCStatus.Not_Eligible;
                obj.SscStatusReason = input.SscStatusReason;
            }

            _uowPatientOpenVisit.Repository.Update(obj!);
            await _uowPatientOpenVisit.CommitAsync();

            return _mapper.Map<CreateorEditPatientEligibleForSSCDto>(obj);
        }

