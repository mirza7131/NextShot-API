        public async Task<CreateOrEditOpenVisitDto> CreateOrEdit(CreateOrEditOpenVisitDto input)
        {
            if (AppCommonMethod.IsNullOrEmptyGuid(input.PatientOpenVisitId))
                return await Create(input);
            else
                return await Update(input);
        }

        private async Task<CreateOrEditOpenVisitDto> Create (CreateOrEditOpenVisitDto input)
        {
            var obj = _mapper.Map<PatientOpenVisit>(input);
            FillEntity(obj);
            input.PatientOpenVisitId = obj.PatientOpenVisitId;
            PatientOpenVisit responseObj = await _uowPatientOpenVisit.Repository.Insert(obj);
            await _uowPatientOpenVisit.CommitAsync();
            return _mapper.Map<CreateOrEditOpenVisitDto>(responseObj);
        }

        private async Task<CreateOrEditOpenVisitDto> Update (CreateOrEditOpenVisitDto input)
        {
            var dbObj = await _uowPatientOpenVisit.Repository.GetById(input.PatientOpenVisitId!);

            if (AppCommonMethod.IsNullObject(dbObj))
                throw new UserFriendlyException(CommonMessageConstant.RecordNotFound);

            var obj = _mapper.Map(input, dbObj);

            FillEntity(obj!);

            _uowPatientOpenVisit.Repository.Update(obj!);
            await _uowPatientOpenVisit.CommitAsync();

            return _mapper.Map<CreateOrEditOpenVisitDto>(obj);

        }

